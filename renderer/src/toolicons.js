/**
 * toolicons.js — 工具栏那 11 颗按钮的**像素画**图标
 *
 * ## 为什么不画彩色，只做「单色剪影」
 *
 * 图是 12×12，在按钮上实际显示也只有 12px。这个尺寸下多色只会糊成一团，
 * 单色剪影才是唯一看得清的画法 —— 而且它换来三件白拿的好处：
 *
 *   1. **金色流动免费**：颜色由 CSS 的 `background` 给，形状由这张图当
 *      `mask-image` 裁。流动就是推一下 `background-position`，
 *      直接复用 style.css 里现成的 `@keyframes border-flow`
 *   2. `.locked` / `:hover` / `.active` 换色也免费 —— 改 CSS 的 background
 *      就行，不用重画图、不用多带一份资源
 *   3. 任何 dpr 下都不糊：canvas 按**设备像素**建，每格边界用 `Math.round`
 *      对齐（见 toolIconMaskUrl 里那段）
 *
 * 这三条正是 style.css:1407 那段注释要的东西 ——「用 emoji 会破坏整体风格，
 * 加个图片文件又得为 11px 的图标多带一份资源」。像素矩阵两者都不是。
 *
 * ## 数据形状
 *
 * `'#'` 是实心，`'.'` 是透明。**每张图必须是 12 行、每行正好 12 个字符** ——
 * 自检和 sim 都盯着这一条（见下方 ICON_SIZE）。手抖少打一个点，
 * 画出来是「右边被啃掉一块」，肉眼在 12px 下根本看不出来。
 *
 * ⚠ 这个模块**顶层不碰 document**。`tools/simulate.js` 是无头跑的，
 *   它要能 import 进来断言这些字符串矩阵；只有真正要生成 mask 的
 *   `toolIconMaskUrl()` 里才建 canvas
 */

