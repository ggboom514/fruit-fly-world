/**
 * 一张图里有多少格是实的。
 *
 * 自检用它挡住「复制粘贴出一个空图标」—— 只断言「有这个键」的话，
 * 一张全 `'.'` 的图照样过，而屏幕上就是一颗空按钮
 */
export function iconFillCount(id) {
	const px = TOOL_ICONS[id]
	if (!px) return 0
	let n = 0
	for (const row of px) for (const ch of row) if (ch === '#') n++
	return n
}

/**
 * 把一张像素图画到 canvas 上（**图鉴**用的那条路）。
 *
 * 和 `toolIconMaskUrl` 的分工：那个是给工具栏按钮做 CSS mask 的（单色、
 * 尺寸由 CSS 决定）；这个是直接画格子，**格子边长自己定**，所以图鉴里
 * 想画多大画多大，而且永远是硬边的方块，不会糊。
 *
 * 以 (ox, oy) 为**中心**画。
 *
 * @param {number} cell 一格多少像素。整数最干净（2 → 24×24 的图）
 */
export function drawPixelIcon(ctx, id, cell, ox, oy, color) {
	const px = TOOL_ICONS[id]
	if (!px) return
	ctx.fillStyle = color
	const half = (ICON_SIZE * cell) / 2
	for (let y = 0; y < ICON_SIZE; y++) {
		for (let x = 0; x < ICON_SIZE; x++) {
			if (px[y][x] !== '#') continue
			ctx.fillRect(ox - half + x * cell, oy - half + y * cell, cell, cell)
		}
	}
}

/**
 * 把一张像素图变成 `mask-image` 能用的 data URL。
 *
 * 白字画在透明底上 —— mask 只认 **alpha 通道**，颜色随便，
 * 但用白色最不容易让人误会「这里能改颜色」（真正决定颜色的是 CSS 的 background）。
 *
 * @param {string} id `TOOL_ICONS` 的键
 * @param {number} dpr `window.devicePixelRatio`。缩放屏上按 1 倍建图会糊
 * @returns {string} data URL；认不出的 id 返回空串（调用方负责别把空串塞进 CSS）
 */
export function toolIconMaskUrl(id, dpr = 1) {
	const px = TOOL_ICONS[id]
	if (!px) return ''

	const size = Math.round(ICON_SIZE * dpr)
	const cv = document.createElement('canvas')
	cv.width = size
	cv.height = size
	const ctx = cv.getContext('2d')
	ctx.fillStyle = '#fff'
	ctx.imageSmoothingEnabled = false

	for (let y = 0; y < ICON_SIZE; y++) {
		const row = px[y]
		for (let x = 0; x < ICON_SIZE; x++) {
			if (row[x] !== '#') continue
			// ⚠ 每格的边界用 `Math.round(格子号 × dpr)` **分别算**，
			//   不是「起点 + round(dpr)」。后者在 dpr=1.25 这种非整数倍下
			//   会累积出 1 设备像素的缝，图标上出现一道道竖白线 ——
			//   而那种线在 12px 下只会被读成「画得有点脏」
			const x0 = Math.round(x * dpr)
			const x1 = Math.round((x + 1) * dpr)
			const y0 = Math.round(y * dpr)
			const y1 = Math.round((y + 1) * dpr)
			ctx.fillRect(x0, y0, x1 - x0, y1 - y0)
		}
	}
	return cv.toDataURL()
}
