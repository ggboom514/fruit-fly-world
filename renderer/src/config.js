/**
 * 食物轮廓的**最大半径 ÷ size**。
 *
 * `drawAppleScrap` 把顶点画在 `size/2 × (0.66 ~ 1.22)` 处，所以最宽的那个角
 * 伸到 `size × 0.61`。凡是「要保证整个果子落在某块区域里」的地方都得用这个数
 * （目前是 `world.dropFoods` 的投放区内缩）。
 *
 * ⚠ 它是**从绘制那边反推出来的**，两处必须一起改 —— 所以放在这里当唯一来源，
 *   render.js 的顶点系数也用这个常量，而不是各写一份 1.22
 */
export const FOOD_DRAW_RADIUS = 0.61

/** 数字工具：把 v 夹在 [lo, hi] 之间 */
export function clamp(v, lo, hi) {
	return v < lo ? lo : v > hi ? hi : v
}

/** 在 [lo, hi) 区间取随机数 */
export function rand(lo, hi) {
	return lo + Math.random() * (hi - lo)
}

/** 在 [lo, hi] 区间取随机整数 */
export function randInt(lo, hi) {
	return Math.floor(lo + Math.random() * (hi - lo + 1))
}

/**
 * 幼虫身体某处的半径系数（相对最大半宽）。
 * @param {number} t 0 = 头，1 = 尾
 */
export function larvaProfileAt(t) {
	const P = CONFIG.larva.profile
	const x = t * (P.length - 1)
	const i = Math.floor(x)
	if (i >= P.length - 1) return P[P.length - 1]
	return P[i] + (P[i + 1] - P[i]) * (x - i)
}

/**
 * 幼虫的最大半宽 ÷ 体长。
 * @param {number} slim 0 = 短胖椭圆，1 = 细长米粒
 */
export function larvaWidthRatio(slim) {
	return CONFIG.larva.widthFat + (CONFIG.larva.widthSlim - CONFIG.larva.widthFat) * slim
}

/**
 * 吃到某种食物时，年龄推进速度的倍率。
 *
 * 认不出来的类型（包括 null —— 也就是没在吃东西）一律返回 1，
 * 所以调用方可以直接把「当前在吃什么」原样丢进来，不用自己判空。
 *
 * @param {string|null|undefined} type 食物的 type 字段
 */
export function foodGrowthBonus(type) {
	const g = CONFIG.food.growthBonus
	return (g && g[type]) || 1
}

/**
 * 警报器等级：0 = 不亮，1 = 橙（快到点了），2 = 红（马上就到）。
 *
 * 抽成纯函数是为了能**精确**测边界 —— 阈值判断卡在 20% / 10% 上，
 * 靠肉眼看光环颜色永远分不清 20.1% 和 19.9% 该亮哪一档。
 *
 * ⚠ 它只回答「这只蝇该不该亮」。**「只管罐子里的」那条规则不在这里** ——
 * 那是调用方的事（render.js 只对 jar.flies 调用它）。
 * 外面的果蝇拿进来问，它照样会算出一个等级。
 *
 * @param {{age:number, lifespan:number, dead?:boolean}|null} fly
 */
export function alarmLevel(fly) {
	const item = CONFIG.market.shop.find((it) => it.id === 'alarm')
	if (!item || !fly || fly.dead || !fly.lifespan) return 0
	// ⚠ wounds 要写成 `|| 0`。这个函数不止被真果蝇调用 ——
	//   tools/simulate.js 是拿 `{ age, lifespan, dead }` 这种**手工对象**来测边界的，
	//   那些对象上根本没有 wounds 字段。写成 fly.age + fly.wounds 的话会得到
	//   undefined → NaN → left = NaN → 两个比较都是 false → 恒返回 0，
	//   而症状是「警报器完全不亮」，看不出跟伤害有什么关系
	const used = fly.age + (fly.wounds || 0)
	const left = 1 - clamp(used / fly.lifespan, 0, 1)
	if (left <= item.warnRed) return 2
	if (left <= item.warnOrange) return 1
	return 0
}

/**
 * 食物投放区（屏幕像素）。
 *
 * 配置里存的是归一化比例，这里换成像素 —— 换分辨率不会变形，
 * 而调用方（world 撒点、ui 画参考框）拿到的永远是同一份换算结果，
 * 不会出现「框画在这儿、苹果落在那儿」。
 */
export function foodZoneRect(w, h) {
	const z = CONFIG.food.zone
	return { x: z.x * w, y: z.y * h, w: z.w * w, h: z.h * h }
}

/**
 * 指针位置 → **苍蝇拍拍面圆心**。
 *
 * 拍子是斜着拿的：指针那一点是握把末端，拍面在它的左上方一段距离外。
 * 杀伤判定和绘制必须都用这个函数的结果，否则两者会各偏各的 ——
 * 而那种偏差的症状是「明明看着拍中了，果蝇却没死」，凭手感几乎查不出来。
 *
 * 数学：把局部坐标 (0, -d)（也就是「指针正上方 d 像素」）绕原点转 swatAngle。
 * 返回的是世界坐标，调用方直接用。
 *
 * @returns {{x: number, y: number}} 拍面圆心
 */
export function swatterHeadAt(mx, my) {
	const T = CONFIG.tools
	const d = T.swatRadius * T.swatReachFactor
	const a = T.swatAngle
	// 旋转公式展开：rotate((0, -d), a) = (d·sin a, -d·cos a)
	return { x: mx + Math.sin(a) * d, y: my - Math.cos(a) * d }
}

/**
 * 按关键帧插值求幼虫体型。
 * sizeKeys 是 [{t: 分钟, size: 像素}]，超出最后一帧就取最后一帧的值。
 */
export function larvaSizeAt(ageMs, keys = CONFIG.larva.sizeKeys) {
	const minutes = ageMs / MIN
	if (minutes <= keys[0].t) return keys[0].size

	for (let i = 1; i < keys.length; i++) {
		const a = keys[i - 1]
		const b = keys[i]
		if (minutes <= b.t) {
			const k = (minutes - a.t) / (b.t - a.t || 1)
			return a.size + (b.size - a.size) * k
		}
	}
	return keys[keys.length - 1].size
}

/**
 * 子代体型性状的遗传：群体均值 + (母体 − 均值) × 遗传力 + 抖动，再夹回合法区间。
 *
 * 那个「向均值回归」的项是必需的，不是调味的：
 * 如果直接让子代 = 母体 + 抖动，性状就是个无约束的随机游走，
 * 挂机跑几十代之后会漂到区间边缘，整屏幼虫全变成同一种极端体型。
 * 有了回归项，均值就是稳定不动点，群体层面的多样性可以一直保持。
 *
 * （这其实就是育种里那条 breeder's equation 的简化版。）
 */
export function inheritTrait(parentValue, lo, hi) {
	const mean = (lo + hi) / 2
	const jitter = (hi - lo) * CONFIG.larva.traitJitter
	const value = mean + (parentValue - mean) * CONFIG.larva.traitHeritability + rand(-1, 1) * jitter
	return clamp(value, lo, hi)
}
